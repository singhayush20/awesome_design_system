// Text enums for semantic typography variants and color roles

/// Semantic text variants following Material 3 typography guidelines.
enum TextVariant {
  displayLarge,
  displayMedium,
  displaySmall,
  headlineLarge,
  headlineMedium,
  headlineSmall,
  titleLarge,
  titleMedium,
  titleSmall,
  bodyLarge,
  bodyMedium,
  bodySmall,
  labelLarge,
  labelMedium,
  labelSmall,
}

/// Semantic text color roles.
enum TextColorRole {
  primary,
  secondary,
  tertiary,
  inverse,
  error,
  outline,
}
